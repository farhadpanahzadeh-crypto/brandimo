/* Generates the static site: one .html file per page in the repository root,
   plus assets/js/search-index.js. Run with `npm run build`. */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { getSearchIndex } from "./data.mjs";
import { allPages } from "./pages.mjs";
import { layout } from "./partials.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const pages = allPages();
for (const page of pages) {
  writeFileSync(join(root, page.file), layout(page));
}

writeFileSync(
  join(root, "assets/js/search-index.js"),
  `/* Generated by build/build.mjs. Do not edit by hand. */\nwindow.BRANDIMO_SEARCH = ${JSON.stringify(getSearchIndex(), null, 1)};\n`,
);

console.log(`Built ${pages.length} pages.`);
